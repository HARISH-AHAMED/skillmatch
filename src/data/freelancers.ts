function buildFreelancer(seed: Seed, index: number): Freelancer {
  return {
    id: seed.id,
    userId: `u-${seed.id}`,
    name: seed.name,
    email: `${seed.id.replace("fl-", "")}@frivvo.talent`,
    avatarUrl: pickFrom(PORTRAITS, index),
    bannerUrl: pickFrom(COMPANY_BANNERS, index, 2),
    professionalHeadline: seed.headline,
    bio: seed.bio,
    location: seed.location,
    domain: seed.domain,
    skills: seed.skills,
    experienceYears: seed.years,
    rating: seed.rating,
    reviewCount: seed.reviews,
    completedProjects: seed.completed,
    completionRate: seed.completionRate,
    responseTime: index % 3 === 0 ? "Within 2 hours" : "Within 24 hours",
    availabilityStatus: seed.availability,
    hourlyRate: seed.rate,
    currency: seed.currency,
    languages: seed.languages.map(([name, level]) => ({ name, level })),
    verificationBadges: seed.badges,
    portfolioUrl: `https://${seed.id.replace("fl-", "")}.work`,
    resumeUrl: `/uploads/${seed.id}-resume.pdf`,
    totalEarnings: seed.earnings,
    gender: seed.gender,
    experience: [
      {
        id: `${seed.id}-x1`,
        title: seed.headline.split("—")[0].trim(),
        company: "Independent — via FRIVVO",
        startDate: `${2026 - Math.min(seed.years, 5)}-01`,
        current: true,
        description: `${seed.completed} completed engagements with a ${seed.completionRate}% completion rate.`,
      },
      {
        id: `${seed.id}-x2`,
        title: seed.years > 5 ? "Senior Contributor" : "Contributor",
        company: ["Kestrel Systems", "Halcyon Group", "Meridian Tech", "Fieldwork Co."][index % 4],
        startDate: `${2026 - seed.years}-03`,
        endDate: `${2026 - Math.min(seed.years, 5)}-01`,
        description:
          "Owned delivery on client engagements across product, platform and go-to-market surfaces.",
      },
    ],
    education: [
      {
        id: `${seed.id}-e1`,
        school: [
          "University of Amsterdam",
          "National University of Singapore",
          "University of Cape Town",
          "Universidade de São Paulo",
          "Indian Institute of Technology",
        ][index % 5],
        degree: seed.domain === "Design & UX" ? "BA" : "BSc",
        field: seed.domain,
        startYear: `${2026 - seed.years - 4}`,
        endYear: `${2026 - seed.years}`,
      },
    ],
    portfolioItems: [0, 1, 2].map((i) => ({
      id: `${seed.id}-p${i}`,
      title: [
        "Operator console redesign",
        "Design system rollout",
        "Data pipeline rebuild",
        "Brand and site relaunch",
        "Mobile intake app",
        "Growth attribution overhaul",
      ][(index + i) % 6],
      description:
        "A scoped engagement delivered end to end, with a written decision log and measurable outcome at handover.",
      imageUrl: pickFrom(PORTFOLIO_SHOTS, index, i * 3),
      link: "#",
      tags: seed.skills.slice(0, 3),
    })),
    invites: [],
    apprenticeScore:
      seed.id === "fl-samuel" ? { rating: 4.6, reviews: 3 } : undefined,
  };
}

