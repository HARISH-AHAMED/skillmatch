const now = Date.now();
const iso = (daysOffset: number) => new Date(now + daysOffset * 86_400_000).toISOString();

function buildRounds(seed: Seed): ScreeningRound[] {
  const specs = seed.rounds ?? [];
  return specs.map((r, i) => ({
    id: `${seed.id}-round-${i}`,
    type: r.type ?? "SCREENING_QUESTIONS",
    name: r.name ?? "Screening Questions",
    description: r.description,
    sortOrder: i,
    comingSoon: r.comingSoon,
    questions:
      r.type === "SCREENING_QUESTIONS" || !r.type
        ? [
            {
              id: `${seed.id}-q1`,
              question: `Walk us through one engagement where you did work close to "${seed.title}". What was the hardest decision and what did you decide?`,
              type: "PARAGRAPH" as const,
              required: true,
            },
            {
              id: `${seed.id}-q2`,
              question: "How many hours a week can you commit, and what does your current commitment look like?",
              type: "PARAGRAPH" as const,
              required: true,
            },
            {
              id: `${seed.id}-q3`,
              question: "Share a link to work that is relevant to this engagement.",
              type: "PORTFOLIO" as const,
              required: false,
            },
            {
              id: `${seed.id}-q4`,
              question: "Are you able to overlap with the team for at least four hours a day?",
              type: "YES_NO" as const,
              required: true,
            },
          ]
        : [],
  }));
}

function buildRoles(seed: Seed): ProjectRole[] {
  return (seed.roles ?? []).map((r, i) => ({
    id: `${seed.id}-role-${i}`,
    projectId: seed.id,
    name: r.name,
    description: r.description,
    slots: r.slots,
    allowApprentice: r.apprentice,
    sortOrder: i,
    hiredCount: r.hired,
    apprenticeCount: r.apprentices ?? 0,
  }));
}

function buildProject(seed: Seed, index: number): Project {
  const company = COMPANY_BY_ID.get(seed.companyId)!;
  return {
    id: seed.id,
    companyId: seed.companyId,
    company: {
      id: company.id,
      companyName: company.companyName,
      logoUrl: company.logoUrl,
      location: company.location,
      industry: company.industry,
      trustScore: company.trustScore,
      rating: company.rating,
    },
    title: seed.title,
    description: seed.description,
    category: seed.category,
    subcategory: seed.subcategory,
    domain: seed.category,
    bannerUrl: pickFrom(PROJECT_BANNERS, index),
    status: seed.status,
    priority: seed.priority,
    visibility: seed.visibility,
    isVisible: seed.status !== "DRAFT",
    preferredGender: "ANY",
    freelancersLimit: seed.limit,
    requiredSkills: seed.required,
    preferredSkills: seed.preferred,
    experienceRequired: seed.experience,
    objectives: seed.objectives,
    deliverables: seed.deliverables,
    responsibilities: seed.responsibilities,
    dailyTasks: seed.dailyTasks,
    faq: (seed.faq ?? []).map((f, i) => ({
      id: `${seed.id}-faq-${i}`,
      question: f.q,
      answer: f.a,
      askedBy: f.by,
      askedAt: iso(-seed.daysAgo + i + 1),
      answeredAt: f.a ? iso(-seed.daysAgo + i + 2) : undefined,
    })),
    workingDays: seed.workingDays,
    timingType: seed.timing,
    duration: seed.duration,
    applicationDeadline: seed.dueInDays ? iso(Math.round(seed.dueInDays * 0.25)) : undefined,
    projectStart: seed.dueInDays ? iso(Math.round(seed.dueInDays * 0.3)) : undefined,
    expectedCompletion: seed.dueInDays ? iso(seed.dueInDays) : undefined,
    dueDate: seed.dueInDays ? iso(seed.dueInDays) : undefined,
    compensation: seed.comp,
    roles: buildRoles(seed),
    rounds: buildRounds(seed),
    certificate: {
      ...DEFAULT_CERT,
      signatoryName: seed.certSignatory?.[0] ?? "",
      signatoryDesignation: seed.certSignatory?.[1] ?? "",
      enabled: Boolean(seed.certSignatory),
    },
    applicantCount: seed.applicants,
    hiredCount: seed.hired,
    viewCount: seed.views,
    savedCount: seed.saved,
    createdAt: iso(-seed.daysAgo),
    updatedAt: iso(-Math.max(0, seed.daysAgo - 3)),
  };
}

export const PROJECTS: Project[] = SEEDS.map(buildProject);

export const PROJECT_BY_ID = new Map(PROJECTS.map((p) => [p.id, p]));
